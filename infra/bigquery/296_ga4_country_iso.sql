-- =============================================================================
-- 296_ga4_country_iso.sql
-- Markets Scouting / opportunity index: GA4 country names to ISO-2, and GA4
-- demand per client x day x country.
--
-- GA4 exports geo.country as an English display name ("Czechia", "Türkiye",
-- "Myanmar (Burma)"), not a code. ref.country_names maps every name the
-- Natural Earth atlas (world-atlas, also used by the Markets map) knows plus
-- GA4's own spellings to ISO-2. An unmatched name stays visible in the view
-- as iso2 NULL with its name, never silently dropped.
--
-- mart.market_ga4_country_daily reads stg.ga4_sessions (loaded daily by the
-- scheduled query ga4_sessions_daily, ops.sp_load_ga4_sessions(3)).
-- Unpaid demand = engaged sessions from Organic, Direct, Referral, Email, AI
-- and similar channels; Paid*, Cross-network and Unassigned are excluded
-- (Unassigned is mostly bot traffic: Dobias 79k sessions, 4 % engaged).
-- =============================================================================

