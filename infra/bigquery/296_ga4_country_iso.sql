CREATE OR REPLACE VIEW `oneeighty-warehouse.mart.market_ga4_country_daily`
OPTIONS (description = 'GA4 sessions per client x day x country (ISO-2): sessions, engaged sessions, unpaid engaged sessions, purchases. Reads stg.ga4_sessions. Migration 296.')
AS
SELECT
  s.client_id,
  s.date,
  c.iso2,
  NULLIF(s.country, '')                                             AS country_name,
  COUNT(*)                                                          AS sessions,
  COUNTIF(s.engaged)                                                AS engaged_sessions,
  COUNTIF(s.engaged AND NOT (STARTS_WITH(IFNULL(s.channel_group, ''), 'Paid')
                            OR s.channel_group IN ('Cross-network', 'Unassigned')
                            OR s.channel_group IS NULL))            AS unpaid_engaged_sessions,
  COUNTIF(s.has_add_to_cart)                                        AS add_to_cart_sessions,
  SUM(IFNULL(s.purchases, 0))                                       AS purchases
FROM `oneeighty-warehouse.stg.ga4_sessions` s
LEFT JOIN `oneeighty-warehouse.ref.country_names` c
  ON c.name = s.country
WHERE s.session_kind = 'session'
GROUP BY s.client_id, s.date, c.iso2, country_name;
