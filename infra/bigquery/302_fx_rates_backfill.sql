      STRUCT(DATE '2026-10-01' AS month_start, 'USD' AS from_currency, 'CZK' AS to_currency, NUMERIC '21.766' AS rate, 'cnb_mtd_avg@2026-10-15' AS source),
      STRUCT(DATE '2026-10-01', 'EUR', 'CZK', NUMERIC '24.405', 'cnb_mtd_avg@2026-10-15'),
      STRUCT(DATE '2026-10-01', 'CZK', 'EUR', NUMERIC '0.04097521', 'cnb_mtd_avg@2026-10-15_inverse')
])) S
ON  T.month_start = S.month_start AND T.from_currency = S.from_currency AND T.to_currency = S.to_currency
WHEN MATCHED AND T.source LIKE '%mtd_avg%' THEN UPDATE SET
  rate = S.rate, source = S.source, ingested_at = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (month_start, from_currency, to_currency, rate, source, ingested_at)
VALUES (S.month_start, S.from_currency, S.to_currency, S.rate, S.source, CURRENT_TIMESTAMP());

