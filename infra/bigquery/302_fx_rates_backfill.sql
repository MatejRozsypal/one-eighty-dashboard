-- Purpose:   fill the holes in ref.fx_rates that leave Dobias CA orders (and a few small
--            OTHER-market orders) without a local-currency rate in mart.market_orders, and
--            refresh the October provisional CNB rows. Full reasoning, numbers and the
--            standing refresh procedure: docs/sessions/2026-10-15/markets/FX-FIX.md.
--
--            What is inserted (nothing is invented; every value is the mean of the source's
--            published daily rates for the month):
--              CAD->USD  2026-06 .. 2026-10   Bank of Canada Valet, series FXCADUSD, mean of
--                                             the daily rates, 4 dp. Same source and method as
--                                             the 012 seed (reproduces 46 of its 48 months
--                                             exactly, the other 2 differ by 0.0001).
--                                             2026-10 is provisional (10 daily rates to 2026-10-15).
--              EUR->USD  2022-06 .. 2026-10   ECB euro foreign exchange reference rates
--              GBP->USD  2022-06 .. 2026-10   (eurofxref-hist.zip, public, no key). Mean of the
--              GBP->EUR  2022-06 .. 2026-10   daily rate; GBP->USD = USD/GBP quoted per EUR;
--                                             GBP->EUR = 1 / GBP quoted per EUR. 6 dp.
--                                             2026-10 is provisional (11 daily rates to 2026-10-15).
--            What is refreshed: the three CNB rows for 2026-10 (USD->CZK, EUR->CZK, CZK->EUR)
--            are provisional (cnb_mtd_avg@2026-10-04, 2 fixings). They are re-computed from the
--            11 daily CNB fixings of 2026-10-01 .. 2026-10-15 (runbook 23 method).
--
-- Two statements, independent of each other (the owner can approve A and skip B):
--              A  new pairs / months (inserts only).
--              B  October CNB refresh (updates three provisional rows; moves October CZK figures
--                 by -0.25 % for EUR orders, about -371 CZK RawBark and -45 CZK Manami to date).
-- Generated by: A  python3 infra/fx_rates_refresh.py --from 2022-06 --today 2026-10-15 \
--                    --pairs CAD/USD@2026-06 EUR/USD GBP/USD GBP/EUR
--               B  python3 infra/fx_rates_refresh.py --from 2026-10 --today 2026-10-15 \
--                    --pairs USD/CZK EUR/CZK CZK/EUR
--               Re-running later regenerates the same closed months and newer ones.
--
-- Cross-check:  Shopify's own conversion implied by the payload presentment amounts of Dobias
--               orders is within 0.3 % of these monthly means (CAD 2026-06 .. 2026-10: 0.7112,
--               0.7075, 0.7207, 0.7146, 0.7018 vs 0.7123, 0.7089, 0.7195, 0.7163, 0.7021).
--
-- Safety:       the MERGE inserts new keys and updates ONLY rows whose source is provisional
--               (T.source LIKE '%mtd_avg%'). No final row that exists today can change: the 5 CAD
--               rows and the 159 EUR/USD, GBP/USD, GBP/EUR rows are new keys; the 3 CNB rows are
--               the existing provisional October rows. Idempotent. A missing rate stays NULL: no
--               "latest rate" fallback is added anywhere (plan P0-5).
--               Readers of these pairs: mart.sp_refresh_market_orders (290: local currency of the
--               order, local->base or 1 / base->local). stg.stg_shopify_orders and the 213 ad-spend
--               joins look up other pairs (shop currency -> client currency, ad currency ->
--               client currency), so their output does not change; CNB October provisional
--               values do feed the USD/EUR/CZK conversions for October, as every refresh does.
-- Needs:        owner OK. NOT EXECUTED against prod.
-- Then:         CALL `oneeighty-warehouse.mart.sp_refresh_markets`();  (or wait for the daily
--               markets_refresh_daily scheduled query once ROLLOUT step 7 has created it).
--
-- Not included (separate decision, history changes): CAD->USD before 2022-06, see FX-FIX.md D.

